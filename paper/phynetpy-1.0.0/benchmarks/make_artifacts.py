"""
Turn the benchmark JSON files into the manuscript's tables and figures.

Nothing numeric in the paper is typed by hand: every table under ``tables/``
and every performance figure under ``figures/`` is written by this script from
the JSON that the ``bench_*.py`` scripts produce.  Re-running the benchmarks and
then this script is the only way those numbers change.

Run (after the bench_* scripts):

    python paper/phynetpy-1.0.0/benchmarks/make_artifacts.py
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from common import load  # noqa: E402

PAPER = Path(__file__).resolve().parents[1]
TABLES = PAPER / "tables"
FIGURES = PAPER / "figures"
TABLES.mkdir(exist_ok=True)
FIGURES.mkdir(exist_ok=True)

PREAMBLE = (
    "% Generated by benchmarks/make_artifacts.py -- do not edit by hand.\n"
)


def write_table(name: str, body: str) -> None:
    path = TABLES / f"{name}.tex"
    path.write_text(PREAMBLE + body, encoding="utf-8")
    print(f"  wrote {path.relative_to(PAPER)}")


def save_figure(fig: Any, name: str) -> None:
    for suffix in ("pdf", "png"):
        path = FIGURES / f"{name}.{suffix}"
        fig.savefig(path, bbox_inches="tight", dpi=200)
    plt.close(fig)
    print(f"  wrote {(FIGURES / (name + '.pdf')).relative_to(PAPER)}")


# ---------------------------------------------------------------------------
# Table: substitution-model transition matrices
# ---------------------------------------------------------------------------
def table_substitution() -> None:
    data = load("core")["substitution_models"]
    rows = []
    for name, entry in data.items():
        rows.append(
            f"{name} & {entry['kind']} & {entry['phynetpy_us']:.2f} & "
            f"{entry['scipy_expm_us']:.2f} & {entry['speedup']:.1f}$\\times$ & "
            f"{entry['max_abs_diff']:.1e} \\\\"
        )
    body = (
        "\\begin{tabular}{llrrrr}\n\\toprule\n"
        "Model & Implementation & \\textsc{PhyNetPy} & \\texttt{expm} & "
        "Ratio & $\\max|\\Delta|$ \\\\\n"
        " & & ($\\mu$s) & ($\\mu$s) & & \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    write_table("substitution_models", body)


# ---------------------------------------------------------------------------
# Table: graph core vs NetworkX
# ---------------------------------------------------------------------------
def table_graph_core() -> None:
    data = load("core")["graph_core"]
    largest = data["1000_leaves"]
    ops = largest["ops"]
    rows = []
    labels = {
        "in_edges lookup": "Incident in-edges of a node",
        "out_degree": "Out-degree of a node",
        "get_leaves": "Enumerate all leaves",
        "topological_order": "Topological order",
        "leaf_descendants_all": "Leaf descendants, all nodes",
    }
    for key, label in labels.items():
        entry = ops.get(key, {})
        phy = entry.get("phynetpy_us")
        nx_us = entry.get("networkx_us")
        ratio = entry.get("ratio_nx_over_phy")
        rows.append(
            f"{label} & {phy:.2f} & "
            + (f"{nx_us:.2f}" if nx_us is not None else "---")
            + " & "
            + (f"{ratio:.2f}$\\times$" if ratio is not None else "---")
            + " \\\\"
        )
    mem = (
        f"Peak construction memory (KiB) & {largest['phynetpy_peak_kib']:.0f} & "
        f"{largest['networkx_peak_kib']:.0f} & "
        f"{largest['memory_ratio_nx_over_phy']:.2f}$\\times$ \\\\"
    )
    body = (
        "\\begin{tabular}{lrrr}\n\\toprule\n"
        "Operation & \\textsc{PhyNetPy} & NetworkX & Ratio \\\\\n"
        " & ($\\mu$s) & ($\\mu$s) & (NetworkX\\,/\\,\\textsc{PhyNetPy}) \\\\\n"
        "\\midrule\n"
        + "\n".join(rows)
        + "\n\\midrule\n"
        + mem
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    write_table("graph_core", body)


# ---------------------------------------------------------------------------
# Table: head-to-head against PhyloNet
# ---------------------------------------------------------------------------
def table_phylonet() -> None:
    data = load("phylonet")
    if "conditions" not in data:
        write_table(
            "phylonet",
            "% Benchmark did not run: " + str(data.get("error", "unknown")) + "\n",
        )
        return
    def num(value: Any, places: int = 2) -> str:
        return f"{value:.{places}f}" if isinstance(value, (int, float)) else "---"

    reps = data["meta"]["comparison"]["replicates_per_condition"]
    rows = []
    exact = {"default": 0, "phylonet": 0, "pn": 0}
    trials = 0

    for entry in data["conditions"].values():
        agg = entry["aggregate"]
        dflt = agg["phynetpy"]["default"]
        phnt = agg["phynetpy"]["phylonet"]
        pn = agg["phylonet"]

        exact["default"] += dflt["exact_recoveries"]
        exact["phylonet"] += phnt["exact_recoveries"]
        exact["pn"] += pn["exact_recoveries"]
        trials += reps

        rows.append(
            f"{entry['taxa']} & {entry['gene_trees']} & "
            f"{entry['reticulations_in_truth']} & "
            f"{agg['concordance_mean'] * 100:.0f}\\% & "
            f"{num(dflt['runtime_s']['mean'])} & "
            f"{num(phnt['runtime_s']['mean'])} & "
            f"{num(pn['runtime_s']['mean'])} & "
            f"{dflt['exact_recoveries']}/{reps} & "
            f"{phnt['exact_recoveries']}/{reps} & "
            f"{pn['exact_recoveries']}/{reps} \\\\"
        )

    summary = (
        f"\\midrule\n\\multicolumn{{7}}{{@{{}}l}}"
        f"{{\\textbf{{Total}}}} & "
        f"\\textbf{{{exact['default']}/{trials}}} & "
        f"\\textbf{{{exact['phylonet']}/{trials}}} & "
        f"\\textbf{{{exact['pn']}/{trials}}} \\\\"
    )

    body = (
        "\\begin{tabular}{rrrrrrrrrr}\n\\toprule\n"
        "& & & & \\multicolumn{3}{c}{Mean runtime (s)} & "
        "\\multicolumn{3}{c}{Replicates recovering truth} \\\\\n"
        "\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}\n"
        "Taxa & Genes & $r$ & Conc. & \\textsc{PNPy} & \\textsc{PNPy} & "
        "PhyloNet & \\textsc{PNPy} & \\textsc{PNPy} & PhyloNet \\\\\n"
        "& & & & (default) & (\\texttt{phylonet}) & & (default) & "
        "(\\texttt{phylonet}) & \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n"
        + summary
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    write_table("phylonet", body)


# ---------------------------------------------------------------------------
# Table: marker likelihood timing
# ---------------------------------------------------------------------------
def table_snp() -> None:
    data = load("snp")["configurations"]
    rows = []
    for entry in data.values():
        rows.append(
            f"{entry['taxa']} & {entry['sites']} & "
            f"{entry['warm_per_call_s'] * 1000:.2f} & "
            f"{entry['log_likelihood']:.1f} \\\\"
        )
    body = (
        "\\begin{tabular}{rrrr}\n\\toprule\n"
        "Taxa & Sites & Time per score (ms) & $\\log L$ \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    write_table("snp", body)


# ---------------------------------------------------------------------------
# Table: compiled kernel A/B
# ---------------------------------------------------------------------------
def table_kernels() -> None:
    data = load("kernels").get("mpl_engine", {})
    if "error" in data:
        write_table("kernels", "% " + data["error"] + "\n")
        return
    rows = []
    for entry in data.values():
        rows.append(
            f"{entry['taxa']} & {entry['gene_trees']} & "
            f"{entry['cython_ms']:.2f} & {entry['python_ms']:.2f} & "
            f"{entry['speedup']:.2f}$\\times$ & {entry['abs_diff']:.1e} \\\\"
        )
    body = (
        "\\begin{tabular}{rrrrrr}\n\\toprule\n"
        "Taxa & Genes & Compiled (ms) & Python (ms) & Ratio & "
        "$|\\Delta \\log \\mathrm{PL}|$ \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    write_table("kernels", body)


# ---------------------------------------------------------------------------
# Table: testing and continuous integration
# ---------------------------------------------------------------------------
def table_testing() -> None:
    data = load("testsuite")
    suite, areas, ci = data["suite"], data["areas"], data["ci"]
    run = suite["default_run"]
    names = {
        "substitution_models": "Substitution models (\\texttt{GTR.py})",
        "network_comparison": "Network comparison and decomposition",
        "network_core": "Network representation and topology moves",
        "inference_api": "Inference API and dispatch registry",
        "phylonet_crosscheck": "PhyloNet numerical cross-check",
        "memory_and_mutation_cost": "Memory and mutation-cost bounds",
    }
    rows = [
        f"{label} & {areas[key]['collected']} \\\\"
        for key, label in names.items()
        if key in areas
    ]
    versions = ", ".join(ci["python_versions"])
    body = (
        "\\begin{tabular}{lr}\n\\toprule\n"
        "Area & Tests \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\midrule\n"
        f"\\textbf{{Total collected}} & \\textbf{{{suite['collected_total']}}} \\\\\n"
        f"Passing in the default run & {run['passed']} \\\\\n"
        f"Deselected as \\texttt{{slow}} & {run['deselected']} \\\\\n"
        f"Failing & {run['failed']} \\\\\n"
        "\\midrule\n"
        f"\\multicolumn{{2}}{{l}}{{Wall time, default run: "
        f"{suite['wall_seconds']:.0f}\\,s}} \\\\\n"
        f"\\multicolumn{{2}}{{l}}{{CI Python versions: {versions}}} \\\\\n"
        f"\\multicolumn{{2}}{{l}}{{CI jobs: "
        f"{', '.join(ci['jobs'])}}} \\\\\n"
        "\\bottomrule\n\\end{tabular}\n"
    )
    write_table("testing", body)


# ---------------------------------------------------------------------------
# Figure: performance
# ---------------------------------------------------------------------------
def figure_performance() -> None:
    core = load("core")
    snp = load("snp")
    phylonet = load("phylonet")

    fig, axes = plt.subplots(1, 3, figsize=(13, 3.6))

    # (a) head-to-head runtime against PhyloNet, aggregated by taxon count.
    # Conditions are scattered rather than joined, because two conditions can
    # share a taxon count with different gene-tree counts; a connecting line
    # would imply a trend across a variable that is not on the axis.
    ax = axes[0]
    if "conditions" in phylonet:
        pnp_x, pnp_y, pn_x, pn_y = [], [], [], []
        for entry in phylonet["conditions"].values():
            agg = entry["aggregate"]
            mean = agg["phynetpy"]["default"]["runtime_s"]["mean"]
            if mean:
                pnp_x.append(entry["taxa"])
                pnp_y.append(mean)
            pn_mean = agg["phylonet"]["runtime_s"]["mean"]
            if pn_mean:
                pn_x.append(entry["taxa"])
                pn_y.append(pn_mean)
        ax.scatter(pnp_x, pnp_y, marker="o", color="C0", label="PhyNetPy")
        ax.scatter(pn_x, pn_y, marker="s", color="C3", label="PhyloNet")
        ax.set_xlabel("Taxa")
        ax.set_ylabel("Mean runtime (s)")
        ax.set_yscale("log")
        ax.set_title("(a) Pseudo-likelihood search, same input")
        ax.legend(fontsize=7, frameon=False)

    # (b) marker likelihood scaling in sites
    ax = axes[1]
    by_taxa: dict[int, list[tuple[int, float]]] = {}
    for entry in snp["configurations"].values():
        by_taxa.setdefault(entry["taxa"], []).append(
            (entry["sites"], entry["warm_per_call_s"] * 1000)
        )
    for taxa in sorted(by_taxa):
        points = sorted(by_taxa[taxa])
        ax.plot(
            [p[0] for p in points],
            [p[1] for p in points],
            marker="o",
            label=f"{taxa} taxa",
        )
    ax.set_xlabel("Sites")
    ax.set_ylabel("Time per score (ms)")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_title("(b) Biallelic-marker likelihood")
    ax.legend(fontsize=7, frameon=False)

    # (c) dissimilarity measures scaling in taxa
    ax = axes[2]
    metrics: dict[str, list[tuple[int, float]]] = {}
    for entry in core["distances"].values():
        for name, stats in entry["metrics"].items():
            metrics.setdefault(name, []).append((entry["taxa"], stats["ms"]))
    for name in sorted(metrics):
        points = sorted(metrics[name])
        ax.plot(
            [p[0] for p in points],
            [p[1] for p in points],
            marker="o",
            label=name.replace("_", " "),
        )
    ax.set_xlabel("Taxa")
    ax.set_ylabel("Time (ms)")
    ax.set_yscale("log")
    ax.set_title("(c) Dissimilarity measures")
    ax.legend(fontsize=7, frameon=False)

    fig.tight_layout()
    save_figure(fig, "performance")


def main() -> None:
    print("Generating tables")
    table_substitution()
    table_graph_core()
    table_phylonet()
    table_snp()
    table_kernels()
    table_testing()
    print("Generating figures")
    figure_performance()


if __name__ == "__main__":
    main()
